import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));

const SOURCES = {
  claude: "https://cdn.jsdelivr.net/npm/@lobehub/icons-static-svg@latest/icons/claude.svg",
  codex: "https://cdn.jsdelivr.net/npm/@lobehub/icons-static-svg@latest/icons/codex.svg",
  opencode: "https://cdn.jsdelivr.net/npm/@lobehub/icons-static-svg@latest/icons/opencode.svg",
  cursor: "https://cdn.jsdelivr.net/npm/@lobehub/icons-static-svg@latest/icons/cursor.svg",
  copilot: "https://cdn.jsdelivr.net/npm/@lobehub/icons-static-svg@latest/icons/copilot.svg",
  apple: "https://cdn.jsdelivr.net/npm/simple-icons@13/icons/apple.svg",
  linux: "https://cdn.jsdelivr.net/npm/simple-icons@13/icons/linux.svg",
  windows: "https://cdn.jsdelivr.net/npm/simple-icons@13/icons/windows.svg",
};

/** Pull every <path> out of an SVG document, keeping its fill rule. */
function extractPaths(svg) {
  const paths = [];
  const re = /<path\b([^>]*)\/?>/g;
  let m;
  while ((m = re.exec(svg))) {
    const attrs = m[1];
    const d = (attrs.match(/\bd="([^"]+)"/) || [])[1];
    if (!d) continue;
    const fillRule = (attrs.match(/\bfill-rule="([^"]+)"/) || [])[1] || null;
    const clipRule = (attrs.match(/\bclip-rule="([^"]+)"/) || [])[1] || null;
    paths.push({ d, fillRule, clipRule });
  }
  return paths;
}

/** Read the viewBox, falling back to width/height when it is missing. */
function extractViewBox(svg) {
  const vb = (svg.match(/\bviewBox="([^"]+)"/) || [])[1];
  if (vb) return vb.trim();
  const w = (svg.match(/\bwidth="([\d.]+)"/) || [])[1];
  const h = (svg.match(/\bheight="([\d.]+)"/) || [])[1];
  return w && h ? `0 0 ${w} ${h}` : "0 0 24 24";
}

const out = {};
const report = [];

for (const [name, url] of Object.entries(SOURCES)) {
  try {
    const res = await fetch(url);
    if (!res.ok) throw new Error(`HTTP ${res.status}`);
    const svg = await res.text();
    const paths = extractPaths(svg);
    if (!paths.length) throw new Error("no <path> found");
    out[name] = { viewBox: extractViewBox(svg), paths };
    report.push(`${name.padEnd(10)} ${String(paths.length).padStart(2)} path(s)  viewBox ${out[name].viewBox}`);
  } catch (err) {
    report.push(`${name.padEnd(10)} FAILED — ${err.message}`);
  }
}

// simple-icons dropped the Windows mark over trademark policy, so it is
// constructed here. The 2021 logo is four flat squares with a 2-unit gutter
// and a 0.55 corner radius — no perspective, no gradient.
function windowsMark() {
  const s = 9;      // square size
  const gap = 2;    // gutter
  const r = 0.55;   // corner radius
  const o = 2;      // outer margin
  const cell = (x, y) =>
    `M${x + r} ${y}H${x + s - r}A${r} ${r} 0 0 1 ${x + s} ${y + r}` +
    `V${y + s - r}A${r} ${r} 0 0 1 ${x + s - r} ${y + s}` +
    `H${x + r}A${r} ${r} 0 0 1 ${x} ${y + s - r}` +
    `V${y + r}A${r} ${r} 0 0 1 ${x + r} ${y}Z`;
  return {
    viewBox: "0 0 24 24",
    paths: [
      {
        d: [
          cell(o, o),
          cell(o + s + gap, o),
          cell(o, o + s + gap),
          cell(o + s + gap, o + s + gap),
        ].join(""),
        fillRule: null,
        clipRule: null,
      },
    ],
  };
}

if (!out.windows) {
  out.windows = windowsMark();
  report.push("windows    constructed (4 panes)");
}

const body = `/**
 * logos.mjs — real brand marks, extracted as raw path data.
 * 実ブランドのロゴ（パスデータ）。
 *
 * GENERATED by fetch-logos.mjs. Do not edit by hand.
 * Generated ${new Date().toISOString().slice(0, 10)}
 *
 * Each entry is { viewBox, paths: [{ d, fillRule, clipRule }] }.
 * All marks render in a single flat colour so they sit in one row.
 *
 * These are trademarks of their owners, used to state compatibility.
 *
 * Made by Nitin Sharma.
 */

export const LOGOS = ${JSON.stringify(out, null, 2)};
`;

writeFileSync(join(HERE, "logos.mjs"), body, "utf8");
process.stdout.write(report.join("\n") + "\n");
process.stdout.write(`\nlogos.mjs written — ${(body.length / 1024).toFixed(1)} KB\n`);
