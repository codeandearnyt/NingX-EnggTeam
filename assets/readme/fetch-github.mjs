/**
 * fetch-github.mjs — writes github.mjs, the one-path GitHub mark.
 * 1 パスの GitHub マークを書き出す。
 */

import { writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));

const res = await fetch("https://cdn.jsdelivr.net/npm/simple-icons@latest/icons/github.svg");
if (!res.ok) {
  console.error(`fetch failed: ${res.status}`);
  process.exit(1);
}

const svg = await res.text();
const d = svg.match(/ d="([^"]+)"/)?.[1];
if (!d) {
  console.error("no path in the svg");
  process.exit(1);
}

const out = `/**
 * github.mjs — the GitHub mark as raw path data, 24×24 viewBox.
 * GitHub マークのパスデータ（24×24）。Generated by fetch-github.mjs.
 */

export const GITHUB_PATH =
  ${JSON.stringify(d)};
`;

await writeFile(join(HERE, "github.mjs"), out, "utf8");
console.log(`github.mjs written — ${d.length} chars of path`);
